CREATE FUNCTION set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_station_master_set_updated_at
    BEFORE UPDATE ON station_master
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

